"""要验证码时，跟用户说的那段话。

## 为什么单独一个模块

    要验证码的地方有四处：
        guard.send_code_email   危险操作 / 提权 / 动作守卫拦截 / 解锁
        netauth.send_code       联网外传
        auditor_code            审计员
        task_perms              升权限

    原来每处各写各的文案，措辞不一致 ——
    有的说"验证码已发到邮箱"，有的说"把这个码回复给前台"，
    用户碰到的提示前后不一样，看不出是同一套东西。

    现在统一从这里取。

## 这段话要说清五件事

    一、**为什么**要码（是哪条规则触发的）
    二、**关掉会失去什么**（列清楚哪几样不保护了）
    三、**不关也行**（填码做这一次）
    四、**关了多久恢复**（用户自己说时间）
    五、**中途反悔可以提前恢复**（这条最容易漏，也最让用户安心）

## ⚠️ 措辞上的一条原则

    不吓唬人，也不含糊。用户是成年人，告诉他事实：
    "这几样暂时不保护了"，而不是"风险自负哈"。

    同时一定要给出"随时可以叫停"这条路 ——
    否则用户会觉得关了就收不回来了，反而不敢关。
"""

from __future__ import annotations

# 关掉验证码期间，到底少了哪些保护。
#
# ⚠️ 这份清单必须跟实际上被关的东西一致。
#    改了 quiet 的覆盖面，这里也要跟着改 ——
#    不然提示里说的和实际做的不一样，那就成了骗人。
PROTECTIONS = [
    "动作守卫（拦截 rm -rf、格式化这类不可逆操作）",
    "影子执行（改动先放影子里，确认后才落地）",
    "危险操作确认（删库、改系统目录这类先问你）",
    "提权验证（把某个窗口的权限从「工作区」放宽）",
    "联网授权（任务自己往外发数据）",
    "审计员（另一个模型盯着每一步改得对不对）",
]


def why_line(reason: str) -> str:
    """第一段：为什么会有这条提示。"""
    r = (reason or "").strip()
    if not r:
        return "这一步需要你确认一下。"
    return f"**为什么要验证码**：{r}"


def protections_block() -> str:
    """第二段：关掉这段时间，哪些保护会停。"""
    items = "\n".join(f"  · {p}" for p in PROTECTIONS)
    return (
        "**这段时间里下面这些会暂时停掉**：\n"
        f"{items}\n\n"
        "到点自动恢复，不用你记。"
    )


def options_block() -> str:
    """第三段：用户可以怎么选。"""
    return (
        "**你有两种走法**：\n\n"
        "  一、**只做这一次** —— 把邮箱里的码发给我，"
        "这一步放行，其余照旧。\n\n"
        "  二、**关一段时间** —— 也是先把码给我，另外说一句关到什么时候，"
        "比如「关到下午五点」「关两个小时」。\n"
        "      这段时间里上面那些都不会再弹码打扰你。"
    )


def howto_block() -> str:
    """第四段：码怎么用、怎么反悔。"""
    return (
        "**码填在哪里**：直接把码发回给我就行，我帮你提交。\n\n"
        "**中途想恢复**：随时说一句「把验证恢复」，立刻生效，不用码。"
    )


def full_text(reason: str = "", email_hint: str = "") -> str:
    """完整的一段（给聊天里看的）。

    ## ⚠️ **绝对不能把邮箱地址放进来**

        原来这里写的是「验证码已经发到 sx***@163.com」。

        看着打了星号，但：
            · 前台是模型，这句会原样带回对话；
            · 对话会被截图、被翻记录、被别的流程转走；
            · 星号只遮了三位，剩下的能猜。

        而且更糟的是：**它告诉了对方"验证码走的是哪个邮箱"**。
        下一步就是去撞那个邮箱的密码。

        （2026-11-05：老爸当场指出了这一点。）

        所以：只说到"你设置的安全邮箱"，**不给任何地址形态**。
        用户自己配的邮箱，他自己知道是哪个；
        别人从这句话里什么都拿不到。
    """
    parts = [
        why_line(reason),
        "验证码已经发到你设置的安全邮箱里了。",
        protections_block(),
        options_block(),
        howto_block(),
    ]
    return "\n\n".join(parts)


def email_body(reason: str, code: str, ttl_minutes: int) -> str:
    """邮件正文。

    ⚠️ 邮件里**不写"你可以关掉验证"**。

        邮件只有一个用处：证明"户主本人看到了这条"。
        在邮件里教用户关闸门，等于把"要不要关"的引导
        放到了一个攻击者也能读到的位置（如果他拿到了你的邮箱）。

        关不关、关多久 —— 这些在聊天里说，那里有上下文。
    """
    r = (reason or "").strip() or "有人要求执行一个需要确认的操作"

    return (
        "有人在这台电脑上要求执行一个需要你确认的操作。\n\n"
        f"原因：{r}\n\n"
        f"验证码：{code}\n\n"
        f"这个码 {ttl_minutes} 分钟内有效，只能用一次。\n\n"
        "如果这不是你要求的 —— **什么都不要做**。\n"
        "同时建议检查一下你的账号有没有被别人登录。\n"
    )
