"""安全审核员的流程。

## 一句话

    审计只问一次。
    用户用验证码证明"我就是户主" —— 然后他自己决定关不关。

## 完整流程

```
任务端跑命令
    ↓
影子执行扣住改动
    ↓
审核员审（guard/auditor.py 的 review）
    ↓
    ├─ pass  → 正常落地
    ├─ block ↓
    └────────┘

        **第一次命中**（这个进程里第一次）
            ↓
        发验证码到用户邮箱
            ↓
        通告前台：「有人要改 X，要验证码。是你在干活吗？」
            ↓
            ├─ 用户填对码  → 证明是本人 → **审计关掉** → 全部落地
            └─ 码没来/填错 → 不是本人 → **锁死任务端**

        **第二次及以后命中**
            审计已经关了 → 直接过，不再问
            或者任务端已经锁了 → 直接拒，什么都干不了
```

## 为什么只问一次就够

    这是解并发问题的关键。

    如果没有"证明身份"这一步，每个改动都要一个码：
        5 个任务 → 5 个码 → 用户不知道哪个对哪个

    加了这一步之后，码不是"某个改动的通行证"，
    而是"你就是户主"的证明。

    证明过了，他自己决定关不关审计 ——
    关了就关了，因为那是本人的决定。

    所以：**一次询问，全局面。**

## 单向

```
前台 → 用户     ✅  通告
用户 → 前台     ✅  给码
前台 → 任务端   ❌  **不能**

任务端永远不知道审查结果。
它被拦住之后，不知道该找谁商量、该说什么话。
```

这跟"审查员不能对话"是同一个道理：
**任何可以让它"沟通"的通道，都是可以被利用的通道。**

## 和现有 guard 的关系

    现有的 guard（危险操作验证码、三次锁死）管的是**动作**：
        删库、回滚代码、读密钥

    审计员管的是**改动的内容**：
        削弱校验、往外发、覆盖文件

    两套**分开计**：
        审计命中不等于"这个人在攻击"，不该算进三次锁死
        guard 的三次锁死是"这个人在尝试突破防线"，性质不同

    但**共用一个码**（同一个邮箱、同一套发信）：
        用户感觉是"一个码"，内部是两条独立的闸。

## 现在是什么状态

    review() 里还是空实现（一律 pass）。
    这份文件先放流程骨架，等 review() 写完再接上。
"""

from __future__ import annotations

# 审计的三种状态
STATE_PASS = "pass"          # 正常，不用管
STATE_OFF = "off"            # 用户已经关掉了（证明过身份）
STATE_LOCKED = "locked"      # 码没来，任务端锁死
STATE_ASKING = "asking"      # 正在等用户填码


def describe() -> str:
    """一句话说清这个审计员在干什么。给界面和日志用。"""
    return (
        "安全审核员：另开一个模型，只看这次改动对不对。"
        "不能对话、没有记忆、不读项目。"
        "命中时会要验证码 —— 一次证明，之后你自己决定关不关。"
    )
